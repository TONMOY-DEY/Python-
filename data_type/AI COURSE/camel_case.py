#Pascal Case কী?

#Pascal Case হলো একটি naming convention, যেখানে একাধিক word-এর মধ্যে কোনো space থাকে না এবং প্রতিটি word-এর প্রথম letter Capital হয়।

Myvariable="Tonmoy"
print(Myvariable)

#Snake Case কী?

#Snake Case হলো একটি naming convention, যেখানে একাধিক word-এর মধ্যে space না দিয়ে underscore _ ব্যবহার করা হয় এবং সাধারণত সব letters ছোট হাতের (lowercase) থাকে।

